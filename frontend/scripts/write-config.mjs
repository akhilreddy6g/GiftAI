// Writes src/app/core/config/app-config.values.ts from environment variables, so no
// project-specific value is committed. Runs before every start, build and test.
//
// Values come from the process environment first, then from the repository's root .env
// (the same file the backend and Docker Compose read). None of them is a secret: the
// Supabase anon key is a public, publishable key.
//
//   GIFTAI_API_URL     where the API lives (default http://localhost:8000)
//   SUPABASE_URL       the Supabase project URL
//   SUPABASE_ANON_KEY  the Supabase anon / publishable key
//
// Missing Supabase values still produce a working build: the app then explains on the
// sign-in page that sign-in isn't set up, which keeps CI and fresh clones building.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseEnv } from 'node:util';

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const rootEnvFile = resolve(frontendRoot, '..', '.env');
const outputFile = resolve(frontendRoot, 'src/app/core/config/app-config.values.ts');

const fromFile = existsSync(rootEnvFile) ? parseEnv(readFileSync(rootEnvFile, 'utf8')) : {};

function read(name, fallback = '') {
  const value = process.env[name] ?? fromFile[name] ?? fallback;
  return value.trim();
}

function normalizeUrl(name, value) {
  if (!value) return '';
  try {
    const url = new URL(value);
    if (url.protocol !== 'https:' && url.protocol !== 'http:') throw new Error('not http(s)');
    return url.toString().replace(/\/+$/, '');
  } catch {
    console.error(`write-config: ${name} must be an http(s) URL, got "${value}".`);
    process.exit(1);
  }
}

const config = {
  apiUrl: normalizeUrl('GIFTAI_API_URL', read('GIFTAI_API_URL', 'http://localhost:8000')),
  supabaseUrl: normalizeUrl('SUPABASE_URL', read('SUPABASE_URL')),
  supabaseAnonKey: read('SUPABASE_ANON_KEY'),
};

// The example values in .env.example mean "not configured yet".
if (config.supabaseUrl.includes('your-project-ref') || config.supabaseAnonKey.startsWith('your-')) {
  config.supabaseUrl = '';
  config.supabaseAnonKey = '';
}

const contents = `// Generated by scripts/write-config.mjs. Do not edit or commit.
import type { AppConfig } from './app-config';

export const APP_CONFIG_VALUES: AppConfig = ${JSON.stringify(config, null, 2)};
`;

writeFileSync(outputFile, contents);
const signIn = config.supabaseUrl && config.supabaseAnonKey ? 'configured' : 'not configured';
console.log(`write-config: API at ${config.apiUrl}, sign-in ${signIn}.`);
